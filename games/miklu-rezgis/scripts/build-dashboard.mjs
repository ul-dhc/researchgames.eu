import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const root=new URL('../',import.meta.url);
export async function buildDashboard(){
 let html=await readFile(new URL('apps-script/Dashboard.html',root),'utf8');
 html=html.replace('  <base target="_top">\n','').replace('  <script src="https://www.gstatic.com/charts/loader.js"></script>','  <script src="https://www.gstatic.com/charts/loader.js"></script>\n  <script src="snapshot-model.js?v=20261029-json-1"></script>\n  <script src="snapshot-loader.js?v=20261029-json-1"></script>');
 html=html.replace('      loadData();\n    });', '      if (dashboardData) renderCharts(dashboardData);\n    });');
 const start=html.indexOf('    function loadData() {'),end=html.indexOf('    function renderDashboard(data)',start);
 if(start<0||end<0)throw new Error('Dashboard template changed');
 html=html.slice(0,start)+`    let snapshotModel = null;
    let snapshotLoading = null;
    function snapshotNotice() {
      if (DashboardSnapshot.stale()) setStatus(currentLang === 'en'
        ? 'Showing saved data; awaiting an update.' : 'Redzami saglabātie dati; gaida atjaunošanu.');
    }
    async function loadData() {
      try {
        if (!snapshotModel) {
          setStatus(currentLang === 'en' ? 'Loading data…' : 'Ielādē datus…');
          if (!snapshotLoading) snapshotLoading = DashboardSnapshot.load(function(data) { snapshotModel = data; loadData(); });
          snapshotModel = await snapshotLoading;
        }
        renderDashboard(RiddleSnapshot.query(snapshotModel, {
          days: $('period').value, version: $('version').value,
          participation: $('participation').value, ...activeFilters
        }));
        snapshotNotice();
      } catch (error) {
        snapshotLoading = null;
        setStatus(currentLang === 'en' ? 'Could not load data. Please try again later.'
          : 'Datus neizdevās ielādēt. Lūdzu, mēģiniet vēlāk.', true);
      }
    }
    setInterval(async function() {
      if (document.hidden) return;
      try { snapshotModel = await DashboardSnapshot.refresh(); loadData(); }
      catch (error) { snapshotNotice(); }
    }, 300000);

`+html.slice(end);
 html=html.replace('  </script>\n</body>', '    loadData();\n  </script>\n</body>');
 await writeFile(new URL('stats/index.html',root),'<!-- Generated by scripts/build-dashboard.mjs from apps-script/Dashboard.html. -->\n'+html);
 const model=await readFile(new URL('stats/snapshot-model.js',root),'utf8');
 await writeFile(new URL('apps-script/SnapshotModel.gs',root),model);
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)await buildDashboard();
